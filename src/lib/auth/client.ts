import { env } from 'cloudflare:workers';
import type { NodeSavedSession, NodeSavedState } from '@atproto/oauth-client-node';
import { buildAtprotoLoopbackClientMetadata, NodeOAuthClient } from '@atproto/oauth-client-node';

export const SCOPE = 'atproto';

// Use globalThis to persist across Next.js hot reloads
const globalAuth = globalThis as unknown as {
	stateStore: Map<string, NodeSavedState>;
	sessionStore: Map<string, NodeSavedSession>;
};
globalAuth.stateStore ??= new Map();
globalAuth.sessionStore ??= new Map();

let client: NodeOAuthClient | null = null;

// Rewrites requests whose URL starts with `canonicalUrl` to use `directUrl` instead.
// Used in devnet to redirect https://devnet.test/* → http://pds:3000/* without requiring
// DNS resolution or TLS certificates for the devnet host inside the worker container.
// The DPoP `htu` claim is unaffected: it is generated by the OAuth client from the
// canonical URL before our fetch is called, and the PDS validates it against its own
// configured public URL (PDS_HOSTNAME), not the incoming request URL.
function createCanonicalRewriteFetch(baseFetch: typeof fetch, canonicalUrl: string, directUrl: string): typeof fetch {
	// Strip trailing slashes so startsWith + slice arithmetic is consistent.
	const canonical = canonicalUrl.replace(/\/$/, '');
	const direct = directUrl.replace(/\/$/, '');
	return async (input: Parameters<typeof fetch>[0], init?: Parameters<typeof fetch>[1]) => {
		const urlStr = input instanceof Request ? input.url : String(input);
		if (urlStr.startsWith(canonical)) {
			const rewritten = direct + urlStr.slice(canonical.length);
			if (input instanceof Request) {
				return baseFetch(new Request(rewritten, input), init);
			}
			return baseFetch(rewritten, init);
		}
		return baseFetch(input, init);
	};
}

export async function getOAuthClient(): Promise<NodeOAuthClient> {
	if (client) return client;

	const { ATPROTO_PDS_URL: pdsUrl, ATPROTO_PLC_URL: plcUrl, ATPROTO_PDS_CANONICAL_URL: pdsCanonicalUrl } = env;
	const oauthFetch = pdsCanonicalUrl ? createCanonicalRewriteFetch(globalThis.fetch, pdsCanonicalUrl, pdsUrl) : globalThis.fetch;

	client = new NodeOAuthClient({
		fetch: oauthFetch,
		// AtprotoHandleResolverNode wraps every fetch with safeFetchWrap which
		// requires Node.js undici — unavailable in workerd. Passing a string URL
		// makes NodeOAuthClient use XrpcHandleResolver instead, which calls
		// com.atproto.identity.resolveHandle over plain globalThis.fetch.
		handleResolver: pdsUrl,
		// Default plcDirectoryUrl is https://plc.directory — override for devnet
		// so did:plc:* DIDs are resolved against the local PLC, not the public one.
		plcDirectoryUrl: plcUrl,
		// Allow http:// resource metadata and issuer URLs for devnet (PDS_HOSTNAME=localhost).
		allowHttp: pdsCanonicalUrl.startsWith('http:'),
		clientMetadata: buildAtprotoLoopbackClientMetadata({
			scope: SCOPE,
			redirect_uris: ['http://127.0.0.1:5173/oauth/callback'],
		}),

		stateStore: {
			async get(key: string): Promise<NodeSavedState | undefined> {
				return globalAuth.stateStore.get(key);
			},
			async set(key: string, value: NodeSavedState): Promise<void> {
				globalAuth.stateStore.set(key, value);
			},
			async del(key: string): Promise<void> {
				globalAuth.stateStore.delete(key);
			},
		},

		sessionStore: {
			async get(key: string): Promise<NodeSavedSession | undefined> {
				return globalAuth.sessionStore.get(key);
			},
			async set(key: string, value: NodeSavedSession): Promise<void> {
				globalAuth.sessionStore.set(key, value);
			},
			async del(key: string): Promise<void> {
				globalAuth.sessionStore.delete(key);
			},
		},
	});

	return client;
}
